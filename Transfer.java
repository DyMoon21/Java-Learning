//基本数据类型的类型转换
public class Transfer {
    public static void main(String[] args) {
        char ch = 'a';
        int i = ch;
        System.out.println(i);

        byte b = (byte)128;
        System.out.println(b);

        float f = (float)3.141592652578787878;
        System.out.println(f);
    }
}
